// Rebuild the five original animation engines and their light scenario styles.
import {fileURLToPath,pathToFileURL} from 'node:url';
import {resolve} from 'node:path';
import {readFile,writeFile} from 'node:fs/promises';
const root=fileURLToPath(new URL('../',import.meta.url));
const esbuild=process.argv[2]
  ? await import(pathToFileURL(resolve(process.argv[2])).href)
  : await import('esbuild');
await esbuild.build({
  entryPoints:[resolve(root,'source/team-dashboards/entry.ts')],
  outfile:resolve(root,'dist/team-dashboards.js'),
  bundle:true,format:'esm',target:'es2020',
  tsconfig:resolve(root,'source/team-dashboards/tsconfig.json'),
});
// Replace only literal dark UI colours. Layout, state selectors and timing are original.
const palette={
  '#0008':'#21355b1a', '#16202e':'var(--pw-sel)',
  '#21242a':'var(--pw-chip)', '#24262a':'var(--pw-chip)',
  '#25272b':'var(--pw-line)', '#25272c':'var(--pw-line)',
  '#27292d':'var(--pw-line)', '#292b30':'var(--pw-line)',
  '#2a2d32':'#e2e6ed', '#303238':'#e2e6ed', '#35383e':'#cbd2de',
  '#263959':'var(--pw-blue-soft)', '#2b4572':'#c1d0f2',
  '#34363b':'#c2c8d2', '#ccc':'#fff',
  '#e6e7e8':'var(--pw-text)', '#dadcdf':'var(--pw-text-2)',
  '#95b1de':'#4d70bd', '#a4bee9':'#4d70bd', '#b2c8ea':'#4d70bd',
  '#7592c3':'#4d70bd', '#8eaddf':'#27835f',
  '#252018':'#fff8e9', '#54432d':'#ead9b8', '#665030':'#e5cda3',
  '#3a2f20':'#faecca', '#d7ae71':'#946620', '#e0c397':'#77531f', '#a79a87':'#8a7454',
};
const files=['audit-dashboard','it-dashboard-demo','devops-dashboard','security-dashboard','industry-dashboard'];
const sheets=await Promise.all(files.map(name=>readFile(resolve(root,`source/team-dashboards/${name}.css`),'utf8')));
const css=sheets.join('\n').replace(/#[\da-f]{3,8}\b/gi,color=>palette[color.toLowerCase()]??color);
await writeFile(resolve(root,'dist/team-dashboards.css'),'/* Generated by build-team-dashboards.mjs. Original scenario geometry, light palette. */\n'+css);
console.log('Built team-dashboards.js and team-dashboards.css');
